import { gzipSync } from 'node:zlib';
import { readFileSync, writeFileSync } from 'node:fs';

/**
 * Rebuilds src/core/auth/breached-list.data.ts from word lists given as arguments. Keeps what a password could be under the floor of 12
 * characters: a shorter entry is refused by length anyway, so it would only add size. Run: `tsx scripts/build-breached-list.ts <file>...`
 */
const FLOOR = 12;
const words = new Set<string>();
for (const file of process.argv.slice(2)) {
  for (const line of readFileSync(file, 'latin1').split(/\r?\n/)) {
    const w = line.trim().toLowerCase();
    if (w.length >= FLOOR && w.length <= 64 && /^[\x20-\x7e]+$/.test(w)) words.add(w);
  }
}
const sorted = [...words].sort();
const b64 = gzipSync(sorted.join('\n'), { level: 9 }).toString('base64');
writeFileSync('src/core/auth/breached-list.data.ts', `// Generated by scripts/build-breached-list.ts. See docs/AUTH.md for the source and its MIT licence.\nexport const BREACHED_COUNT = ${sorted.length};\nexport const BREACHED_GZ_BASE64 = '${b64}';\n`);
process.stdout.write(`${sorted.length} entries, ${b64.length} bytes of base64\n`);
